<?php

declare(strict_types=1);

namespace App\Http;

use Sahil\Contracts\Assets\AssetManagerContract;
use Sahil\Contracts\Foundation\ApplicationContract;
use Sahil\Contracts\View\ViewContract;
use Sahil\Http\Response;

/**
 * Renders the UI kit example that matches the active asset profile.
 *
 * The controller never builds an asset URL itself. It chooses the sample
 * layout by profile; the layout's `@asset_css`/`@asset_js` helpers and the
 * page's `asset()` calls resolve development and production URLs.
 */
final class UiKitController
{
    public function __construct(
        private readonly ViewContract $views,
        private readonly AssetManagerContract $assets,
        private readonly ApplicationContract $application,
    ) {
    }

    public function response(): Response
    {
        $profile = $this->assets->profile() ?? 'none';

        $view = match ($profile) {
            'bootstrap' => 'examples.bootstrap',
            'tailwind', 'both' => 'examples.tailwind',
            default => 'examples.plain',
        };

        $labels = [
            'tailwind' => 'Tailwind CSS v4 profile',
            'bootstrap' => 'Bootstrap 5 profile',
            'both' => 'Tailwind CSS v4 + Bootstrap 5 profile',
            'none' => 'Plain CSS profile',
        ];

        return Response::html($this->views->render($view, [
            'app_name' => (string) $this->application->config()->get('app.name', 'SahilPHP'),
            'heading' => 'A functional UI page',
            'intro' => 'This page uses shared layout, navigation and component partials. '
                .'Its asset tags are generated by the active UI profile, so the same templates work '
                .'in development and production without hand-built URLs.',
            'profile_label' => $labels[$profile] ?? $profile,
            'form' => [
                'name' => 'Ada Lovelace',
                'email' => 'ada@example.com',
                'role' => 'editor',
                'notes' => 'Ship the page with labels, inline validation and a responsive table.',
            ],
            'errors' => [
                'name' => 'Name is required.',
                'email' => 'Enter a valid email address.',
            ],
            'roles' => [
                'admin' => 'Administrator',
                'editor' => 'Editor',
                'viewer' => 'Viewer',
            ],
            'alerts' => [
                [
                    'type' => 'success',
                    'title' => 'Saved',
                    'message' => 'The record was updated successfully.',
                ],
                [
                    'type' => 'warning',
                    'title' => 'Review needed',
                    'message' => 'One field needs attention before publishing.',
                ],
                [
                    'type' => 'danger',
                    'title' => 'Request failed',
                    'message' => 'Check the highlighted fields and try again.',
                ],
            ],
            'users' => [
                ['Ada Lovelace', 'ada@example.com', 'Editor', 'Active'],
                ['Grace Hopper', 'grace@example.com', 'Administrator', 'Active'],
                ['Alan Turing', 'alan@example.com', 'Viewer', 'Invited'],
            ],
        ]));
    }
}
